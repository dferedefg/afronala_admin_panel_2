/**
 * Creates default country configs for a newly registered or custom module
 */
export function buildDefaultCountryConfigsForModule(
  key: string,
  name: string,
  category: string,
  targetCountries: Exclude<EastAfricaCountryCode, 'ALL'>[] = EAST_AFRICAN_COUNTRIES_ORDERED
): Record<Exclude<EastAfricaCountryCode, 'ALL'>, EastAfricaModuleCountryConfig> {
  const result = {} as Record<Exclude<EastAfricaCountryCode, 'ALL'>, EastAfricaModuleCountryConfig>;

  for (const code of EAST_AFRICAN_COUNTRIES_ORDERED) {
    const meta = EAST_AFRICAN_COUNTRIES_META[code];
    const isTarget = targetCountries.includes(code);

    result[code] = {
      countryCode: code,
      countryName: meta.name,
      flag: meta.flag,
      enabled: isTarget,
      operatingStatus: isTarget ? 'pilot' : 'disabled',
      statusLabel: isTarget ? 'Pilot Sandbox' : 'Disabled',
      regulatoryAuthority: meta.transportRegulator,
      regulatoryFilingNumber: `${code}-${key.toUpperCase()}-REG-2026`,
      statutoryCommissionCapPct: meta.statutoryCommissionCapPct,
      withholdingTaxPct: code === 'KE' ? 5 : code === 'UG' ? 6 : code === 'RW' ? 3 : 2,
      currency: meta.currency,
      primaryPaymentRail: meta.primaryPaymentRail,
      activeFleetCount: isTarget ? 15 : 0,
      supportedCities: [meta.capital],
      primaryHubs: [`${meta.capital} Central Hub`],
      speedLimiterRequired: meta.speedLimiterMandate,
      cashOnDeliveryAllowed: code !== 'RW',
      crossBorderBondedTransit: category === 'Logistics',
      emergencySOSHooked: category === 'Mobility' || category === 'Logistics',
      notes: `Custom registered ${name} (${category}) vertical deployed to ${meta.name}.`,
      updatedAt: new Date().toISOString(),
    };
  }

  return result;
}

/**
 * Calculates high-level statistics for a country or pan-East Africa
 */
export function calculateRegionalModuleStats(
  modules: ModuleItem[],
  countryCode: EastAfricaCountryCode
) {
  if (countryCode === 'ALL') {
    const totalModules = modules.filter((m) => m.key !== 'more').length;
    const globallyActive = modules.filter((m) => m.key !== 'more' && m.enabled).length;
    let totalFleetCount = 0;
    let totalCountryDeployments = 0;

    for (const mod of modules) {
      if (mod.countryConfigs) {
        for (const code of EAST_AFRICAN_COUNTRIES_ORDERED) {
          const cfg = mod.countryConfigs[code];
          if (cfg?.enabled) {
            totalCountryDeployments++;
            totalFleetCount += cfg.activeFleetCount || 0;
          }
        }
      }
    }

    return {
      scopeTitle: 'Pan-East Africa (8 Nations)',
      flag: '🌍',
      totalModules,
      activeCount: globallyActive,
      countryDeployments: totalCountryDeployments,
      totalFleetCount,
      primaryRegulators: 'EAC Secretariat & National Authorities (NTSA, FTA, RURA, LATRA, DTT)',
      avgCommissionCap: 12.8,
      primaryRails: 'Telebirr, M-PESA, MTN MoMo, D-Money, EVC Plus',
    };
  }

  const meta = EAST_AFRICAN_COUNTRIES_META[countryCode];
  let activeInCountry = 0;
  let pilotInCountry = 0;
  let stagedInCountry = 0;
  let disabledInCountry = 0;
  let fleetCount = 0;

  for (const mod of modules) {
    if (mod.key === 'more') continue;
    const cfg = mod.countryConfigs?.[countryCode];
    if (cfg?.enabled) {
      if (cfg.operatingStatus === 'active') activeInCountry++;
      else if (cfg.operatingStatus === 'pilot') pilotInCountry++;
      else stagedInCountry++;
      fleetCount += cfg.activeFleetCount || 0;
    } else {
      disabledInCountry++;
    }
  }

  return {
    scopeTitle: `${meta.name} (${meta.code})`,
    flag: meta.flag,
    totalModules: modules.filter((m) => m.key !== 'more').length,
    activeCount: activeInCountry,
    pilotCount: pilotInCountry,
    stagedCount: stagedInCountry,
    disabledCount: disabledInCountry,
    totalFleetCount: fleetCount,
    primaryRegulators: meta.transportRegulator,
    shortRegulator: meta.shortRegulator,
    statutoryCommissionCap: meta.statutoryCommissionCapPct,
    primaryRails: meta.primaryPaymentRail,
    currency: meta.currency,
    currencySymbol: meta.currencySymbol,
    corridor: meta.corridor,
  };
}
